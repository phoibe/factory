#!/usr/bin/env node
// Archived specs (« specs rangées »): the validated spec of a feature or bug, saved in the project as
// docs/specs/<n>-<slug>.md in the feature's own PR, with a summary docs/specs/README.md rebuilt from the files.
// Usage, from the project's folder:
//   node .factory/scripts/specs.mjs save <n>            save issue <n>'s latest validated spec, rebuild the summary
//   node .factory/scripts/specs.mjs modified <old> <new> mark spec <old> as modified by request <new>
//   node .factory/scripts/specs.mjs index               rebuild the summary from the files
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const DIR = 'docs/specs';
const SPEC_MARK = '<!-- factory-spec -->';

export function slug(title) {
  return String(title || '').normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase()
    .replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 60).replace(/-+$/, '');
}

export function specFileName(n, title) {
  const s = slug(title);
  return s ? `${n}-${s}.md` : `${n}.md`;
}

// The latest comment carrying the spec marker, or null.
export function latestSpec(comments) {
  return [...(comments || [])].filter((c) => String(c.body || '').includes(SPEC_MARK)).at(-1) || null;
}

// The spec's content only: no markers, version heading, signatures, glossary sentence or validation request.
export function cleanSpec(body) {
  let text = String(body || '').replace(/\r\n/g, '\n');
  const footer = text.search(/\n---\s*\n_(Généré par|Generated by)/);
  if (footer >= 0) text = text.slice(0, footer);
  const paragraphs = text.replace(/<!--[\s\S]*?-->/g, '').split(/\n{2,}/).map((p) => p.trim()).filter(Boolean)
    .map((p) => p.replace(/^##\s+Spec\s*\(version[^)]*\)\s*(\n|$)/i, '').trim()).filter(Boolean)
    .filter((p) => !/^(J'ai ajouté au glossaire|Décisions notées)/.test(p));
  while (paragraphs.length && /Répondez/.test(paragraphs.at(-1))) paragraphs.pop();
  return paragraphs.join('\n\n');
}

const issueUrl = (repo, n) => `https://github.com/${repo}/issues/${n}`;
const modifiedLine = (repo, n) => `> Modifiée par la demande n° [#${n}](${issueUrl(repo, n)})`;

export function renderSpec({ repo, n, title, body, date, modifiedBy = [] }) {
  const head = [`> Demande [#${n}](${issueUrl(repo, n)}) · ${date}`, ...modifiedBy.map((m) => modifiedLine(repo, m))];
  return `# ${n} · ${title}\n\n${head.join('\n')}\n\n${String(body).trim()}\n`;
}

export function parseSpec(text) {
  const t = String(text || '');
  const h = /^# (\d+) · (.+)$/m.exec(t);
  const d = /^> Demande \[#\d+\]\([^)]*\) · (\S+)$/m.exec(t);
  const modifiedBy = [...t.matchAll(/^> Modifiée par la demande n° \[#(\d+)\]/gm)].map((m) => Number(m[1]));
  const phrase = /\*\*En une phrase\*\*\s*:\s*(.+)/.exec(t);
  const firstPara = t.split(/\n{2,}/).map((p) => p.trim()).find((p) => p && !/^[#>]/.test(p)) || '';
  const summary = (phrase ? phrase[1] : (/^[^\n]*?[.!?](\s|$)/.exec(firstPara)?.[0] || firstPara.split('\n')[0])).trim();
  return { n: h ? Number(h[1]) : null, title: h ? h[2].trim() : '', summary, date: d ? d[1] : '', modifiedBy };
}

// Adds « Modifiée par la demande n° <newN> » under the header lines, once; the rest is untouched.
export function addModifiedBy(text, repo, newN) {
  if (parseSpec(text).modifiedBy.includes(Number(newN))) return text;
  const lines = String(text).split('\n');
  let i = lines.findIndex((l) => l.startsWith('> Demande '));
  if (i < 0) throw new Error('en-tête de spec introuvable');
  while (lines[i + 1]?.startsWith('> Modifiée par')) i++;
  lines.splice(i + 1, 0, modifiedLine(repo, newN));
  return lines.join('\n');
}

const capitalize = (s) => String(s || '').charAt(0).toUpperCase() + String(s || '').slice(1);
const cell = (s) => String(s || '').replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ');

export function renderIndex(entries) {
  const rows = [...entries].sort((a, b) => a.n - b.n).map((e) => {
    const note = e.modifiedBy.length ? ` Modifiée par ${e.modifiedBy.map((m) => `#${m}`).join(', ')}.` : '';
    return `| ${e.n} | [${cell(e.title)}](${e.file}) | ${cell(capitalize(e.summary))}${note} | ${e.date} |`;
  });
  return ['# Sommaire des specs', '',
    'Chaque spec validée d\'une feature ou d\'un bug, telle qu\'elle a été livrée. Ce sommaire est tenu à jour automatiquement : ne le modifiez pas à la main.',
    '', '| N° | Titre | En une phrase | Date |', '| --- | --- | --- | --- |', ...rows, ''].join('\n');
}

export function writeIndex(dir) {
  const folder = join(dir, DIR);
  mkdirSync(folder, { recursive: true });
  const entries = readdirSync(folder).filter((f) => /^\d+(-.*)?\.md$/.test(f))
    .map((file) => ({ file, ...parseSpec(readFileSync(join(folder, file), 'utf8')) })).filter((e) => e.n !== null);
  writeFileSync(join(folder, 'README.md'), renderIndex(entries));
}

const findSpecFile = (dir, n) => {
  const folder = join(dir, DIR);
  return existsSync(folder) ? readdirSync(folder).find((f) => f === `${n}.md` || f.startsWith(`${n}-`)) || null : null;
};

function defaultGh(path) {
  const get = (p) => JSON.parse(execFileSync('gh', ['api', p], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 }));
  if (!path.endsWith('/comments')) return get(path);
  const all = [];
  for (let page = 1; ; page++) {
    const batch = get(`${path}?per_page=100&page=${page}`);
    all.push(...batch);
    if (batch.length < 100) return all;
  }
}

export async function saveSpec({ dir, repo, n, gh = defaultGh }) {
  const issue = await gh(`repos/${repo}/issues/${n}`);
  const spec = latestSpec(await gh(`repos/${repo}/issues/${n}/comments`));
  if (!spec) throw new Error(`la demande #${n} n'a aucune spec validée (commentaire ${SPEC_MARK})`);
  const existing = findSpecFile(dir, n);
  const keep = existing ? parseSpec(readFileSync(join(dir, DIR, existing), 'utf8')).modifiedBy : [];
  const file = specFileName(n, issue.title);
  mkdirSync(join(dir, DIR), { recursive: true });
  const text = renderSpec({ repo, n, title: issue.title, body: cleanSpec(spec.body), date: String(spec.created_at).slice(0, 10), modifiedBy: keep });
  if (existing && existing !== file) rmSync(join(dir, DIR, existing)); // the title changed since
  writeFileSync(join(dir, DIR, file), text);
  writeIndex(dir);
  return `${DIR}/${file}`;
}

export async function markModified({ dir, repo, old, by }) {
  const file = findSpecFile(dir, old);
  if (!file) throw new Error(`la demande #${old} n'a pas de spec rangée dans ${DIR}`);
  const path = join(dir, DIR, file);
  writeFileSync(path, addModifiedBy(readFileSync(path, 'utf8'), repo, by));
  writeIndex(dir);
  return `${DIR}/${file}`;
}

function repoOf(dir) {
  const remote = execFileSync('git', ['remote', 'get-url', 'origin'], { cwd: dir, encoding: 'utf8' }).trim();
  const m = /github\.com[/:]([^/]+\/[^/.\s]+)/.exec(remote) || /\/git\/([^/]+\/[^/.\s]+)/.exec(remote);
  if (!m) throw new Error(`dépôt GitHub introuvable dans ${remote}`);
  return m[1];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [cmd, a, b] = process.argv.slice(2);
  const dir = process.cwd();
  const num = (x) => { if (!/^\d+$/.test(x || '')) throw new Error('numéro de demande attendu'); return Number(x); };
  try {
    if (cmd === 'save') console.log(`Spec rangée : ${await saveSpec({ dir, repo: repoOf(dir), n: num(a) })} (sommaire à jour).`);
    else if (cmd === 'modified') console.log(`Renvoi ajouté : ${await markModified({ dir, repo: repoOf(dir), old: num(a), by: num(b) })}.`);
    else if (cmd === 'index') { writeIndex(dir); console.log(`Sommaire à jour : ${DIR}/README.md.`); }
    else throw new Error('commande attendue : save <n> | modified <ancienne> <nouvelle> | index');
  } catch (e) {
    console.error(`Specs : ${e.message}`);
    process.exit(1);
  }
}
