export const NO_SHA = '0'.repeat(40);
export const probeUrl = (repo, path, sha) => (path.startsWith('/') ? path : `/repos/${repo}/${path.replace('{sha}', sha)}`);
export const probeSaysWritable = (status) => ![401, 403, 404, 410].includes(status);
// GitHub is unavailable or limiting us: its rate limit is a 403 too, which must never read as « cannot write ».
// `message`: GitHub's own message, the only sign of a secondary rate limit sent without any header (issue #558).
export const githubBusy = (status, headers, message = '') => status >= 500 || status === 429
  || (status === 403 && (headers?.get('x-ratelimit-remaining') === '0' || headers?.has('retry-after') || /rate limit/i.test(String(message))));

// The requests proposed in one answer, as the panel will create them with the full token: never more than the
// server's limit, never anything but a bug or a feature with a title (the chat server is not trusted with writes).
const MAX_ISSUES = 3;
export const wantedIssues = (list) => (Array.isArray(list) ? list : [])
  .filter((i) => i && typeof i.title === 'string' && i.title.trim())
  .slice(0, MAX_ISSUES)
  .map((i) => ({ kind: i.kind === 'bug' ? 'bug' : 'feature', title: i.title.trim().slice(0, 200), body: String(i.body ?? '').slice(0, 60000) }));

// ---- Requests the agent proposes (issue #492) ------------------------------------------------------
// The agent never creates a bug or a feature: it writes a block per request (same format as the chat server's), and
// the panel shows it as a card that only the owner's click turns into a request.
// A block the agent wrapped in a code fence takes its fence with it: no empty code block is left on screen.
const BLOCK = /(?:```[^\n]*\n\s*)?<creer-issue\s+type="([^"]*)"\s+titre="([^"]*)"\s*>([\s\S]*?)<\/creer-issue>(?:\s*\n\s*```)?/g;
// The text comes back as written (images and markers are read afterwards), only without its blocks.
export function proposalsFrom(text) {
  const found = [...String(text || '').matchAll(BLOCK)].map((m) => ({ kind: m[1].trim(), title: m[2], body: m[3].trim() }));
  return { text: String(text || '').replace(BLOCK, '').trim(), proposals: wantedIssues(found) };
}

// Issue mode: the owner's choice on a card is a hidden comment with the agent marker (so the factory does not start
// an agent on it, and the chat shows nothing). The first decision on a card is the one that counts.
// Only a comment that is nothing but a decision counts: an answer of the agent can never mark its own card decided.
const DECISION = /^<!-- factory-agent -->\n<!-- factory-proposal: ([\w-]+) (created|ignored)(?: (\S+))? -->$/;
export const decisionComment = (id, state, url) => `${AGENT_MARKER}\n<!-- factory-proposal: ${id} ${state}${url ? ` ${url}` : ''} -->`;
function decisionsFrom(comments) {
  const out = new Map();
  for (const c of comments) {
    const m = DECISION.exec(String(c.body || '').replace(/\r\n/g, '\n').trim());
    if (m && !out.has(m[1])) out.set(m[1], { state: m[2], url: m[2] === 'created' ? safeGithubUrl(m[3]) : undefined });
  }
  return out;
}

// Server mode: the card's state lives in the stored conversation. False when it was already decided or is unknown.
export function decideProposal(conv, id, state, url) {
  const p = (conv?.messages || []).flatMap((m) => m.proposals || []).find((x) => x.id === id);
  if (!p || p.state !== 'pending') return false;
  p.state = state;
  if (url) p.url = url;
  return true;
}

// Issue #516: a conversation ends by itself once none of its cards waits for the owner's choice and at least one
// request was created from it (ignoring every card keeps it open, as before).
export const finishesConversation = (cards = []) => cards.length > 0
  && cards.every((c) => c.state === 'created' || c.state === 'ignored') && cards.some((c) => c.state === 'created');

// Why a pasted read token is refused, or null when it is fine.
export function readTokenProblem({ same, classic, status, login, owner, readable, writable }) {
  if (same) return WRITABLE_TOKEN;
  if (classic) return CLASSIC_TOKEN;
  if (writable) return WRITABLE_TOKEN;
  if (status === 401) return 'GitHub ne reconnaît pas ce jeton : vérifiez que vous l\'avez collé en entier.';
  if (String(login || '').toLowerCase() !== String(owner || '').toLowerCase()) return 'Ce jeton appartient à un autre compte GitHub que celui du panneau.';
  if (!readable) return 'Ce jeton ne peut pas lire ce projet : sur GitHub, choisissez « All repositories » avant de le créer.';
  return null;
}

// The stored conversation, in the format the chat server used to write (server/chat/core.py).
export const newConversation = (id, firstText, now = '') => ({ id, title: titleFrom(firstText || 'Image envoyée'), state: 'open', created: now, updated: now, messages: [] });

// Older answers carry `issues` (requests created at once, before issue #492); new ones carry pending `proposals`.
// `tag` names this answer's cards: the copy saved and a copy kept on screen (save failed) share it, so they share ids.
export const cardTag = () => globalThis.crypto.randomUUID().slice(0, 8);
export function addExchange(conv, mine, answer, now = '', proposals = [], tag = cardTag()) {
  conv.messages.push({ who: 'me', text: mine.text || '', images: [...(mine.images || [])], at: now });
  const agent = { who: 'agent', text: answer, at: now };
  if (proposals.length) agent.proposals = proposals.map((p, i) => ({ id: `${tag}-${i}`, kind: p.kind, title: p.title, body: p.body, state: 'pending' }));
  conv.messages.push(agent);
  conv.updated = now;
  conv.state = 'open';
  return conv;
}

export function upsertIndex(index, conv) {
  const entry = { id: conv.id, title: conv.title, updated: conv.updated, state: conv.state || 'open' };
  return [entry, ...(index || []).filter((e) => e.id !== conv.id)].sort((a, b) => String(b.updated || '').localeCompare(String(a.updated || '')));
}

// An issue the agent proposed. A feature the owner asked for is kept (never an « idée à trier »), and the agent
// marker leaves it to the queue instead of starting it at once; a bug starts right away.
// The factory's hidden notes are taken out of the proposed text: written with the owner's token they would count.
const NOTES = /<!--\s*factory-[\s\S]*?-->/g;
const withoutNotes = (text) => { let s = String(text ?? ''); for (let prev = null; prev !== s;) { prev = s; s = s.replace(NOTES, ''); } return s; };
export function issueRequest({ kind, title, body }) {
  const text = `${withoutNotes(body)}\n\n_Demandé depuis le chat du tableau de suivi._`;
  return kind === 'bug'
    ? { title, labels: ['factory:bug'], body: text }
    : { title, labels: ['factory:feature', 'factory:kept'], body: `${AGENT_MARKER}\n${text}` };
}

// The conversation id that names `chats/<id>.json`, written with the full token: never taken unchecked from the chat
// server (a path there would aim the owner's full token at another GitHub endpoint). Same rule as the server's.
const CID = /^[A-Za-z0-9_-]{1,64}$/;
export function conversationId(fromServer, current, now = new Date()) {
  if (CID.test(String(current ?? ''))) return current;
  if (CID.test(String(fromServer ?? ''))) return fromServer;
  const at = now.toISOString().replace(/\D/g, '');
  return `${at.slice(0, 8)}-${at.slice(8, 14)}-${Math.random().toString(36).slice(2, 7).padEnd(5, '0')}`;
}
