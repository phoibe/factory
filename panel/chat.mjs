// Pure helpers for the « Agent » tab (tested in test/panel-chat.test.mjs).
// A conversation is a `factory:question` issue: its description is the first message, each comment the next.
// The owner never sees GitHub: the panel shows it as a chat.

export const LABEL = 'factory:question';
const AGENT_MARKER = '<!-- factory-agent -->';
const WAIT_MS = 10 * 60_000; // past this, a message nobody answered is « late »

// The messages behind the two buttons under a conversation. The agent's question stage creates the issue.
export const ASK = {
  feature: 'Créez une issue « Nouvelle feature » à partir de cette conversation, puis donnez-moi le lien.',
  bug: 'Créez une issue « Signaler un bug » à partir de cette conversation, puis donnez-moi le lien.',
};

const names = (labels = []) => labels.map((l) => (typeof l === 'string' ? l : l.name));
const isBot = (user) => user?.type === 'Bot' || /\[bot\]$/.test(user?.login || '');
// On a public project anyone can open an issue or comment: someone without write access is neither the owner
// nor the agent (the agent posts with the owner's account or the factory's bot).
const WRITERS = new Set(['OWNER', 'MEMBER', 'COLLABORATOR']);
export const fromStranger = (x) => Boolean(x?.author_association) && !WRITERS.has(x.author_association) && !isBot(x.user);

// The text of a message as the owner should read it: no hidden marker, no « generated by » footer.
export function cleanBody(body) {
  return String(body || '')
    .replace(/\r\n/g, '\n')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\n+---\n+_(?:Généré par|Message automatique)[^\n]*_\s*$/, '')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

// ---- Images -------------------------------------------------------------------------------------
// An image sent from the chat is stored on the `factory-attachments` branch (the agent reads it there). The
// message carries a hidden marker with its path, which the relay passes to the agent, and a normal Markdown
// image so that it also shows on GitHub.
export const ATTACHMENTS_BRANCH = 'factory-attachments';
const IMAGE_MARK = /<!-- factory-image: (attachments\/chat\/[\w-]+\.(?:png|jpe?g|gif|webp)) -->/g;
const EXT = { 'image/png': 'png', 'image/jpeg': 'jpg', 'image/gif': 'gif', 'image/webp': 'webp' };

// Only GitHub links may become clickable: a link coming from chat data must never run script.
export const safeGithubUrl = (u) => (/^https:\/\/github\.com\/[\w./#?=&%-]*$/.test(String(u || '')) ? u : undefined);

export const imagePath = (type, now = Date.now(), rand = Math.random().toString(36).slice(2, 8)) =>
  `attachments/chat/${now}-${rand}.${EXT[type] || 'jpg'}`;

export const imageBlock = (repo, path) =>
  `<!-- factory-image: ${path} -->\n![capture](https://github.com/${repo}/blob/${ATTACHMENTS_BRANCH}/${path}?raw=true)`;

export function splitImages(body) {
  const images = [...String(body || '').matchAll(IMAGE_MARK)].map((m) => m[1]);
  const text = cleanBody(String(body || '').replace(/^!\[capture\]\(https:\/\/github\.com\/[^)\s]+\/blob\/factory-attachments\/[^)\s]+\)\s*$/gm, ''));
  return { text, images };
}

export function chatMessages(issue, comments = []) {
  const out = [];
  const push = (who, body, item) => {
    const { text, images } = splitImages(body);
    if (text || images.length) out.push({ who, text, ...(images.length ? { images } : {}), at: item.created_at, url: item.html_url });
  };
  push((issue.body || '').includes(AGENT_MARKER) ? 'agent' : 'me', issue.body, issue);
  for (const c of comments) {
    if (fromStranger(c)) continue;
    const body = c.body || '';
    if (body.includes(AGENT_MARKER) && !body.includes('<!-- factory-notified -->')) push('agent', body, c);
    else if (!isBot(c.user)) push('me', body, c);
  }
  return out;
}

// 'thinking' (an agent is on it, or the owner just wrote), 'late' (the owner wrote long ago and nobody answered),
// 'idle' (the agent answered) or 'closed'.
export function chatStatus(issue, messages, now = Date.now()) {
  if (issue.state === 'closed') return 'closed';
  if (names(issue.labels).includes('factory:running')) return 'thinking';
  const last = messages.at(-1);
  if (!last || last.who !== 'me') return 'idle';
  return now - Date.parse(last.at) < WAIT_MS ? 'thinking' : 'late';
}

export function titleFrom(text) {
  const line = String(text || '').trim().split('\n')[0].trim().replace(/\s+/g, ' ');
  if (!line) return 'Discussion';
  return line.length <= 70 ? line : `${line.slice(0, 68).replace(/\s+\S*$/, '')}…`;
}

// Open conversations first, then the finished ones, most recently active first.
export function conversations(issues = []) {
  return issues
    .filter((i) => !i.pull_request && !fromStranger(i))
    .sort((a, b) => (b.state === 'open') - (a.state === 'open') || Date.parse(b.updated_at) - Date.parse(a.updated_at));
}

// seen: { [number]: comment count when the owner last looked }. A conversation never opened is not flagged.
export const unread = (c, seen) => seen[c.number] != null && (c.comments || 0) > seen[c.number];

// Instant mode (chat server): seen is { [id]: the conversation's `updated` time when its answer was last shown }.
export const serverUnread = (c, seen) => seen[c.id] != null && Date.parse(c.updated) > Date.parse(seen[c.id]);

// ---- A small Markdown reader --------------------------------------------------------------------
// Turns the agent's answer into a tree the page builds with DOM nodes (never innerHTML), so nothing in a
// message can run code. Supports what the agent writes: paragraphs, **bold**, *italic*, `code`, links,
// lists, quotes, code blocks; headings show as bold lines.

const SAFE_URL = /^https?:\/\//i;

export function inline(text) {
  const out = [];
  const pushText = (v) => {
    if (!v) return;
    const prev = out.at(-1);
    if (prev?.t === 'text') prev.v += v; else out.push({ t: 'text', v });
  };
  const re = /`([^`\n]+)`|\*\*(.+?)\*\*|\*([^*\s][^*]*?)\*|\[([^\]\n]+)\]\(([^)\s]+)\)|(https?:\/\/[^\s<>()]+)/g;
  let at = 0;
  for (let m; (m = re.exec(text));) {
    pushText(text.slice(at, m.index));
    at = re.lastIndex;
    if (m[1] != null) out.push({ t: 'code', v: m[1] });
    else if (m[2] != null) out.push({ t: 'b', c: inline(m[2]) });
    else if (m[3] != null) out.push({ t: 'i', c: inline(m[3]) });
    else if (m[4] != null) {
      if (SAFE_URL.test(m[5])) out.push({ t: 'a', href: m[5], c: inline(m[4]) });
      else pushText(m[0]);
    } else {
      // A bare link: the sentence's closing punctuation is not part of it.
      const url = m[6].replace(/[.,;:!?'"»]+$/, '');
      out.push({ t: 'a', href: url, c: [{ t: 'text', v: url }] });
      pushText(m[6].slice(url.length));
    }
  }
  pushText(text.slice(at));
  return out;
}

const withBreaks = (lines) => lines.flatMap((l, i) => (i ? [{ t: 'br' }, ...inline(l)] : inline(l)));

export function markdown(text) {
  const lines = String(text || '').replace(/\r\n/g, '\n').split('\n');
  const blocks = [];
  let para = [];
  const flush = () => { if (para.length) blocks.push({ type: 'p', inline: withBreaks(para) }); para = []; };
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (/^\s*```/.test(line)) {
      flush();
      const code = [];
      while (++i < lines.length && !/^\s*```/.test(lines[i])) code.push(lines[i]);
      blocks.push({ type: 'pre', v: code.join('\n') });
      continue;
    }
    if (!line.trim() || /^\s*(-{3,}|\*{3,})\s*$/.test(line)) { flush(); continue; }
    const heading = /^\s*#{1,6}\s+(.*)$/.exec(line);
    if (heading) { flush(); blocks.push({ type: 'p', inline: [{ t: 'b', c: inline(heading[1].trim()) }] }); continue; }
    const list = /^\s*(?:([-*+])|\d+[.)])\s+(.*)$/.exec(line);
    if (list) {
      flush();
      const type = list[1] ? 'ul' : 'ol';
      const prev = blocks.at(-1);
      const item = inline(list[2]);
      if (prev?.type === type && prev.open) prev.items.push(item);
      else blocks.push({ type, items: [item], open: true });
      continue;
    }
    const quote = /^\s*>\s?(.*)$/.exec(line);
    if (quote) {
      flush();
      const prev = blocks.at(-1);
      if (prev?.type === 'quote' && prev.open) prev.inline.push({ t: 'br' }, ...inline(quote[1]));
      else blocks.push({ type: 'quote', inline: inline(quote[1]), open: true });
      continue;
    }
    // An indented line right after a list item continues it.
    const prev = blocks.at(-1);
    if (!para.length && /^\s+\S/.test(line) && prev?.open && (prev.type === 'ul' || prev.type === 'ol')) {
      prev.items.at(-1).push({ t: 'br' }, ...inline(line.trim()));
      continue;
    }
    for (const b of blocks) delete b.open;
    para.push(line);
  }
  flush();
  for (const b of blocks) delete b.open;
  return blocks;
}

// ---- Chat server (server/chat, on Modal) --------------------------------------------------------
// When the factory's chat server is deployed, messages go to it and the answer streams back as NDJSON;
// conversations are JSON files on the project's `factory-chat` branch, no issue involved.
export const CHAT_BRANCH = 'factory-chat';

// Splits what has arrived so far into complete events and the unfinished last line.
export function ndjson(buffer) {
  const lines = buffer.split('\n');
  const rest = lines.pop();
  const events = [];
  for (const l of lines) {
    if (!l.trim()) continue;
    try { events.push(JSON.parse(l)); } catch {}
  }
  return { events, rest };
}

export function serverMessages(conv) {
  return (conv?.messages || [])
    .filter((m) => m.text || m.images?.length)
    .map((m) => ({
      who: m.who === 'agent' ? 'agent' : 'me', text: m.text || '',
      ...(m.images?.length ? { images: m.images } : {}), at: m.at,
      ...(m.issues?.length ? { issues: m.issues } : {}),
    }));
}

export const serverList = (index) => [...(index || [])]
  .sort((a, b) => (b.state === 'open') - (a.state === 'open') || Date.parse(b.updated) - Date.parse(a.updated));

// ---- Read-only token (issue #395) -----------------------------------------------------------------
// The chat server only ever receives a second token that can read the projects, never change them. The panel
// does the writes (conversation, issues) with the full token, which never leaves the browser.
export const READ_TOKEN_KEY = 'factory.chatToken';
export const READ_TOKEN_URL = 'https://github.com/settings/personal-access-tokens/new?name=factory+discussion+lecture&description=Lecture+seule+pour+la+discussion+avec+l%27agent&expires_in=365&contents=read';
export const WRITABLE_TOKEN = 'Ce jeton peut modifier vos projets : créez-en un en lecture seule avec le bouton ci-dessus.';
// A write with an empty body: GitHub refuses a read-only token (403) before reading the body; a token that may write
// gets a 422 (invalid body). Nothing is ever written. Same probe as the server's.
export const WRITE_PROBE = '.factory-write-probe';
export const probeSaysWritable = (status) => ![401, 403, 404].includes(status);

// Why a pasted read token is refused, or null when it is fine.
export function readTokenProblem({ same, status, login, owner, readable, writable }) {
  if (same || writable) return WRITABLE_TOKEN;
  if (status === 401) return 'GitHub ne reconnaît pas ce jeton : vérifiez que vous l\'avez collé en entier.';
  if (String(login || '').toLowerCase() !== String(owner || '').toLowerCase()) return 'Ce jeton appartient à un autre compte GitHub que celui du panneau.';
  if (!readable) return 'Ce jeton ne peut pas lire ce projet : sur GitHub, choisissez « All repositories » avant de le créer.';
  return null;
}

// The stored conversation, in the format the chat server used to write (server/chat/core.py).
export const newConversation = (id, firstText, now = '') => ({ id, title: titleFrom(firstText || 'Image envoyée'), state: 'open', created: now, updated: now, messages: [] });

export function addExchange(conv, mine, answer, now = '', issues = []) {
  conv.messages.push({ who: 'me', text: mine.text || '', images: [...(mine.images || [])], at: now });
  const agent = { who: 'agent', text: answer, at: now };
  if (issues.length) agent.issues = issues.map((i) => ({ title: i.title, url: i.url, kind: i.kind }));
  conv.messages.push(agent);
  conv.updated = now;
  conv.state = 'open';
  return conv;
}

export function upsertIndex(index, conv) {
  const entry = { id: conv.id, title: conv.title, updated: conv.updated, state: conv.state || 'open' };
  return [entry, ...(index || []).filter((e) => e.id !== conv.id)].sort((a, b) => String(b.updated || '').localeCompare(String(a.updated || '')));
}

// An issue the agent proposed. A feature the owner asked for is kept (never an « idée à trier »), and the agent
// marker leaves it to the queue instead of starting it at once; a bug starts right away.
export function issueRequest({ kind, title, body }) {
  const text = `${body}\n\n_Demandé depuis le chat du tableau de suivi._`;
  return kind === 'bug'
    ? { title, labels: ['factory:bug'], body: text }
    : { title, labels: ['factory:feature', 'factory:kept'], body: `${AGENT_MARKER}\n${text}` };
}

