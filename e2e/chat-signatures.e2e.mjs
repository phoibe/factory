// Journeys of issue #482: the chat hides every signature closing an agent message, French and English, even stacked.
import test from 'node:test';
import assert from 'node:assert/strict';
import { withPanel, issue } from './fixture.mjs';

const FR = '\n\n---\n_Généré par [Claude Code](https://claude.ai/code) · software factory_';
const EN = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_';
const at = (s) => new Date(Date.now() - s * 1000).toISOString();
const reply = (text, s) => ({ body: `<!-- factory-agent -->\n${text}`, created_at: at(s), html_url: 'u', user: { login: 'o' }, author_association: 'OWNER' });

test('le dernier message de l\'agent se termine sans « Généré par… » ni « Generated by… », même quand les deux se suivent', async () => {
  const conv = issue(7, 'Signatures visibles', ['factory:question'], { comments: 2, body: 'Bonjour' });
  const comments = { 7: [reply(`Voici la fiche.${FR}`, 30), reply(`C'est fait.${FR}\n${EN}`, 10)] };
  await withPanel({ issues: [conv], comments }, async ({ page, url }) => {
    await page.goto(url);
    await page.getByRole('tab', { name: 'Agent', exact: true }).click();
    await page.locator('.conv', { hasText: 'Signatures visibles' }).click();
    await page.locator('#chat-messages .msg.agent', { hasText: 'C\'est fait.' }).waitFor();
    const texts = await page.locator('#chat-messages .msg.agent').allInnerTexts();
    assert.equal(texts.length, 2);
    for (const t of texts) assert.doesNotMatch(t, /Généré par|Generated by|---/);
    assert.equal(await page.locator('#chat-messages .msg.agent hr').count(), 0);
  });
});
