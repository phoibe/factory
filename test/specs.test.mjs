import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import {
  slug, specFileName, latestSpec, cleanSpec, renderSpec, parseSpec, addModifiedBy, renderIndex, saveSpec, markModified,
} from '../agent/scripts/specs.mjs';

const REPO = 'phoibe/demo';
const SPEC = `<!-- factory-agent -->
<!-- factory-spec -->
## Spec (version 2)

**En une phrase** : les réservations se font en deux clics.

### Règles
- Une seule réservation par personne.

J'ai ajouté au glossaire : « Réservation ».

Je vous demande quand même de valider. Répondez « go » pour lancer la construction.

---
_Généré par [Claude Code](https://claude.ai/code) · software factory_


---
_Generated by [Claude Code](https://claude.ai/code)_`;

test('le nom du fichier est le numéro puis le titre, sans accents ni caractères gênants', () => {
  assert.equal(slug('Réserver un créneau / l\'été « vite » !'), 'reserver-un-creneau-l-ete-vite');
  assert.equal(specFileName(12, 'Réserver un créneau'), '12-reserver-un-creneau.md');
  assert.equal(specFileName(7, '!!!'), '7.md');
  assert.ok(specFileName(3, 'x'.repeat(200)).length <= 70);
});

test('la spec retenue est le dernier commentaire de spec de la demande', () => {
  const comments = [
    { body: '<!-- factory-agent -->\n<!-- factory-spec -->\n## Spec (version 1)\nvieille', created_at: '2026-11-01T10:00:00Z' },
    { body: 'go', created_at: '2026-11-01T11:00:00Z' },
    { body: '<!-- factory-agent -->\n<!-- factory-spec -->\n## Spec (version 2)\nneuve', created_at: '2026-11-02T10:00:00Z' },
    { body: '<!-- factory-agent -->\nJe construis', created_at: '2026-11-03T10:00:00Z' },
  ];
  assert.match(latestSpec(comments).body, /neuve/);
  assert.equal(latestSpec([{ body: 'rien', created_at: 'x' }]), null);
});

test('la spec rangée ne garde que le contenu, sans marqueurs, signatures ni demande de validation', () => {
  const out = cleanSpec(SPEC);
  assert.match(out, /^\*\*En une phrase\*\* : les réservations/);
  assert.match(out, /Une seule réservation par personne\.$/);
  assert.doesNotMatch(out, /factory-|Spec \(version|Généré par|Generated by|Répondez|J'ai ajouté au glossaire/);
});

test('le document commence par le lien vers la demande et la date, et se relit', () => {
  const text = renderSpec({ repo: REPO, n: 12, title: 'Réserver un créneau', body: cleanSpec(SPEC), date: '2026-11-02' });
  assert.match(text, /^# 12 · Réserver un créneau\n\n> Demande \[#12\]\(https:\/\/github\.com\/phoibe\/demo\/issues\/12\) · 2026-11-02\n/);
  assert.deepEqual(parseSpec(text), { n: 12, title: 'Réserver un créneau', summary: 'les réservations se font en deux clics.', date: '2026-11-02', modifiedBy: [] });
});

test('une ancienne spec reçoit une ligne « Modifiée par la demande » sans être réécrite, une seule fois', () => {
  const old = renderSpec({ repo: REPO, n: 12, title: 'Réserver', body: cleanSpec(SPEC), date: '2026-11-02' });
  const once = addModifiedBy(old, REPO, 40);
  const twice = addModifiedBy(addModifiedBy(once, REPO, 40), REPO, 41);
  assert.match(once, /> Modifiée par la demande n° \[#40\]\(https:\/\/github\.com\/phoibe\/demo\/issues\/40\)/);
  assert.equal(once.replace(/> Modifiée par.*\n/, ''), old);
  assert.equal((twice.match(/#40\]/g) || []).length, 1);
  assert.deepEqual(parseSpec(twice).modifiedBy, [40, 41]);
});

test('le sommaire liste chaque spec par numéro, avec titre, phrase, date et renvoi', () => {
  const index = renderIndex([
    { file: '40-b.md', n: 40, title: 'B', summary: 'Deux.', date: '2026-11-05', modifiedBy: [] },
    { file: '9-a.md', n: 9, title: 'A | pipe', summary: 'Un.', date: '2026-11-01', modifiedBy: [40] },
  ]);
  assert.match(index, /^# Sommaire des specs\n/);
  assert.ok(index.indexOf('[A \\| pipe](9-a.md)') < index.indexOf('[B](40-b.md)'));
  assert.match(index, /\| 9 \| \[A \\\| pipe\]\(9-a\.md\) \| Un\. Modifiée par #40\. \| 2026-11-01 \|/);
});

function project() {
  const dir = mkdtempSync(join(tmpdir(), 'specs-'));
  return dir;
}
const fakeGh = (title, comments) => (path) => (path.endsWith('/comments') ? comments : { title, labels: [] });

test('save range la spec et tient le sommaire à jour ; un nouvel enregistrement remplace le même fichier', async () => {
  const dir = project();
  const gh = fakeGh('Réserver un créneau', [{ body: SPEC, created_at: '2026-11-02T10:00:00Z' }]);
  const file = await saveSpec({ dir, repo: REPO, n: 12, gh });
  assert.equal(file, 'docs/specs/12-reserver-un-creneau.md');
  await saveSpec({ dir, repo: REPO, n: 12, gh });
  assert.deepEqual(readdirSync(join(dir, 'docs/specs')).sort(), ['12-reserver-un-creneau.md', 'README.md']);
  assert.match(readFileSync(join(dir, 'docs/specs/README.md'), 'utf8'), /\| 12 \| \[Réserver un créneau\]\(12-reserver-un-creneau\.md\) \| Les réservations se font en deux clics\. \| 2026-11-02 \|/);
});

test('save garde les renvois « Modifiée par » quand la spec est réenregistrée', async () => {
  const dir = project();
  const gh = fakeGh('Réserver', [{ body: SPEC, created_at: '2026-11-02T10:00:00Z' }]);
  const file = await saveSpec({ dir, repo: REPO, n: 12, gh });
  await markModified({ dir, repo: REPO, old: 12, by: 40 });
  await saveSpec({ dir, repo: REPO, n: 12, gh });
  assert.deepEqual(parseSpec(readFileSync(join(dir, file), 'utf8')).modifiedBy, [40]);
});

test('save refuse clairement une demande sans spec, et n\'écrit rien', async () => {
  const dir = project();
  await assert.rejects(saveSpec({ dir, repo: REPO, n: 5, gh: fakeGh('X', [{ body: 'go', created_at: 'x' }]) }), /aucune spec/);
  assert.throws(() => readdirSync(join(dir, 'docs/specs')));
});

test('markModified signale une demande sans spec rangée', async () => {
  const dir = project();
  mkdirSync(join(dir, 'docs/specs'), { recursive: true });
  writeFileSync(join(dir, 'docs/specs/README.md'), '');
  await assert.rejects(markModified({ dir, repo: REPO, old: 3, by: 4 }), /pas de spec rangée/);
});
